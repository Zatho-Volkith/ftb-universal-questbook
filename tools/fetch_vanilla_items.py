"""Snapshot the vanilla item registry for a given Minecraft version.

Vanilla items are the backbone of this library -- the core modules use nothing
else -- but no mod jar contains them, and we do not want validation to depend
on the network or on the user having a client jar unpacked somewhere.

So we fetch once, commit the result, and validate offline forever after. The
source is misode/mcmeta, which publishes per-version registry dumps generated
directly from the game.

Re-run this only when adding support for a new Minecraft version:

    python3 fetch_vanilla_items.py --mc-version 1.21.1
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.error
import urllib.request
from pathlib import Path

SOURCE = "https://raw.githubusercontent.com/misode/mcmeta/{version}-registries/item/data.json"
DEFAULT_OUTPUT_DIR = Path(__file__).parent / "data"


def fetch(version: str, timeout: int = 30) -> list[str]:
    url = SOURCE.format(version=version)
    request = urllib.request.Request(url, headers={"User-Agent": "ftb-universal-questbook"})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            payload = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            raise SystemExit(
                f"no registry dump published for Minecraft {version}.\n"
                f"tried: {url}\n"
                f"check the tag list at https://github.com/misode/mcmeta/tags"
            ) from exc
        raise SystemExit(f"fetch failed ({exc.code} {exc.reason}): {url}") from exc
    except urllib.error.URLError as exc:
        raise SystemExit(f"network error fetching {url}: {exc.reason}") from exc

    if not isinstance(payload, list) or not payload:
        raise SystemExit(f"unexpected payload shape from {url}")
    return payload


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mc-version", default="1.21.1")
    parser.add_argument("-o", "--output", type=Path, default=None)
    args = parser.parse_args(argv)

    paths = fetch(args.mc_version)
    output = args.output or DEFAULT_OUTPUT_DIR / f"vanilla-items-{args.mc_version}.json"

    manifest = {
        "_comment": (
            f"Vanilla item registry for Minecraft {args.mc_version}. "
            "Generated by fetch_vanilla_items.py; do not edit by hand."
        ),
        "_source": SOURCE.format(version=args.mc_version),
        "mc_version": args.mc_version,
        "namespaces": {
            "minecraft": {
                "from_jar": f"vanilla {args.mc_version}",
                "count": len(paths),
                "items": sorted(f"minecraft:{p}" for p in paths),
            }
        },
    }

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"minecraft {args.mc_version}: {len(paths)} items -> {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
